// Copies the SqueekYield and SeedToken ABIs (and SqueekYield's creation bytecode, for the in-app
// deploy) from Foundry's output into src/lib/abi.generated.ts. Without contracts/out (no forge on
// this machine) the committed file is kept as it is.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const out = "contracts/out";
const target = "src/lib/abi.generated.ts";
const pool = `${out}/SqueekYield.sol/SqueekYield.json`;
const seed = `${out}/SeedToken.sol/SeedToken.json`;

if (!existsSync(pool) || !existsSync(seed)) {
  console.log(`abi: ${out} not found, keeping committed ${target} (run \`forge build\` in contracts/ to refresh)`);
  process.exit(0);
}
const p = JSON.parse(readFileSync(pool, "utf8"));
const s = JSON.parse(readFileSync(seed, "utf8"));
writeFileSync(
  target,
  `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit by hand.\n` +
    `export const squeekYieldAbi = ${JSON.stringify(p.abi)} as const;\n\n` +
    `export const seedTokenAbi = ${JSON.stringify(s.abi)} as const;\n\n` +
    `export const squeekYieldBytecode = ${JSON.stringify(p.bytecode.object)} as const;\n`,
);
console.log(`abi: wrote ${target}`);
